/*
    ABOUT: Table Joins

    A table join is used when you want to write a SQL query
    that meets the following conditions:

    1. Posgres requires data from multiple tables to give 
    you an answer to your query.

    2. These tables have a shared column.


    Qualified JOIN: Uses an ON or USING clause to specify how rows match.

    Unqualified JOIN: Has no ON or USING clause, 
    producing a Cartesian product (every row paired with every row).
*/
